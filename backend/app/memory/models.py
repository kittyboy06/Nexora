"""Domain models for Phase 11: Memory and Persistence Platform."""

from enum import Enum
from typing import Any, Optional
from pydantic import BaseModel, ConfigDict, Field


class MemoryCategory(str, Enum):
    """Classification of durable memory records."""

    USER_PREFERENCE = "user_preference"
    PROJECT_FACT = "project_fact"
    SYSTEM_CONSTRAINT = "system_constraint"


class SensitivityLevel(str, Enum):
    """Data sensitivity classification determining review thresholds."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class MemoryStatus(str, Enum):
    """Lifecycle state of a memory record."""

    ACTIVE = "ACTIVE"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    EXPIRED = "EXPIRED"
    REVOKED = "REVOKED"


class MemoryRecord(BaseModel):
    """Durable memory item stored in SQLite and indexed in FTS5."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(..., description="Unique memory record identifier")
    key: str = Field(..., description="Descriptive slug key e.g. pref:test_runner")
    category: MemoryCategory = Field(default=MemoryCategory.PROJECT_FACT)
    value: str = Field(..., description="The stored fact, rule, or preference")
    sensitivity: SensitivityLevel = Field(default=SensitivityLevel.MEDIUM)
    status: MemoryStatus = Field(default=MemoryStatus.ACTIVE)
    provenance_task_id: Optional[str] = Field(default=None, description="Originating task ID")
    provenance_reason: Optional[str] = Field(default=None, description="Justification or evidence quote")
    created_at: str = Field(..., description="ISO 8601 creation timestamp")
    updated_at: str = Field(..., description="ISO 8601 last update timestamp")
    expires_at: Optional[str] = Field(default=None, description="ISO 8601 expiration timestamp (or None)")
    version_hash: str = Field(..., description="Deterministic SHA-256 integrity hash")


class MemoryProposal(BaseModel):
    """Proposal generated by an agent or user to record a new durable memory."""

    model_config = ConfigDict(extra="ignore")

    key: str = Field(..., min_length=1, description="Unique key for the proposed memory")
    category: MemoryCategory = Field(default=MemoryCategory.PROJECT_FACT)
    value: str = Field(..., min_length=1, description="Content of the memory to record")
    sensitivity: SensitivityLevel = Field(default=SensitivityLevel.MEDIUM)
    provenance_task_id: Optional[str] = Field(default=None)
    provenance_reason: str = Field(..., min_length=1, description="Why this fact or preference should be remembered")
    ttl_days: Optional[int] = Field(default=None, ge=1, le=365, description="Retention in days (None for indefinite)")


class MemoryAuditEntry(BaseModel):
    """Immutable audit record for memory lifecycle events."""

    model_config = ConfigDict(extra="ignore")

    id: Optional[int] = None
    memory_id: str
    action: str = Field(..., description="PROPOSE, APPROVE, UPDATE, RECALL, REVOKE, DELETE")
    actor: str = Field(default="agent", description="agent, operator, policy_engine")
    task_id: Optional[str] = None
    details: Optional[str] = None
    timestamp: str


class MemoryQueryRequest(BaseModel):
    """Query payload for recalling memories."""

    model_config = ConfigDict(extra="ignore")

    query: str = Field(..., min_length=1)
    category: Optional[MemoryCategory] = None
    max_results: int = Field(default=5, ge=1, le=50)


class MemoryUpdateRequest(BaseModel):
    """Payload for updating an existing memory record."""

    model_config = ConfigDict(extra="ignore")

    value: Optional[str] = None
    category: Optional[MemoryCategory] = None
    sensitivity: Optional[SensitivityLevel] = None
    expires_at: Optional[str] = None
    reason: Optional[str] = None


class MemoryBackupInfo(BaseModel):
    """Snapshot metadata for database backups."""

    model_config = ConfigDict(extra="ignore")

    backup_path: str
    record_count: int
    file_size_bytes: int
    created_at: str
    is_valid: bool
