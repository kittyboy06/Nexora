"""Domain Models for Phase 10: Generated Tools and Sandbox Platform."""

from enum import Enum
from typing import Any, Optional
from pydantic import BaseModel, ConfigDict, Field


class SandboxRunStatus(str, Enum):
    """Execution status for a sandboxed trial or test run."""

    TESTS_PASSED = "TESTS_PASSED"
    TESTS_FAILED = "TESTS_FAILED"
    TIMEOUT = "TIMEOUT"
    OOM_KILLED = "OOM_KILLED"
    EXECUTION_SUCCESS = "EXECUTION_SUCCESS"
    ERROR = "ERROR"


class TestCase(BaseModel):
    """Positive or negative test case for a proposed tool."""

    __test__ = False
    model_config = ConfigDict(extra="ignore")

    name: str = Field(..., description="Descriptive test case identifier")
    inputs: dict[str, Any] = Field(default_factory=dict, description="Input parameters passed to the tool function")
    expected_output: Any = Field(default=None, description="Expected returned value for positive assertions")
    is_negative: bool = Field(default=False, description="True if test verifies error/exception handling")


class GeneratedToolManifest(BaseModel):
    """Metadata specification describing a validated generated tool."""

    model_config = ConfigDict(extra="ignore")

    name: str = Field(..., pattern=r"^[a-z0-9_]+$", description="Slug tool name identifier")
    version: str = Field(default="1.0.0", description="Semver tool version string")
    description: str = Field(default="", description="Human-readable description of tool capability")
    input_schema: dict[str, Any] = Field(default_factory=dict, description="JSON Schema for parameters")
    output_schema: dict[str, Any] = Field(default_factory=dict, description="JSON Schema for return value")
    test_cases: list[TestCase] = Field(default_factory=list, description="Verified test cases")
    source_sha256: str = Field(..., description="Deterministic SHA-256 hash of validated tool source code")
    created_at: str = Field(..., description="ISO 8601 creation timestamp")


class GeneratedToolProposal(BaseModel):
    """Incoming proposal generated by an agent when encountering a capability gap."""

    model_config = ConfigDict(extra="ignore")

    name: str = Field(..., pattern=r"^[a-z0-9_]+$", description="Unique identifier for the proposed tool")
    description: str = Field(..., min_length=1, description="Description of the tool function")
    code: str = Field(..., min_length=1, description="Complete Python implementation code")
    input_schema: dict[str, Any] = Field(default_factory=dict, description="Expected argument types")
    output_schema: dict[str, Any] = Field(default_factory=dict, description="Expected return type")
    test_cases: list[TestCase] = Field(default_factory=list, description="Positive and negative verification test cases")
    task_id: Optional[str] = Field(default=None, description="Parent task ID requesting the capability")


class SandboxRunResult(BaseModel):
    """Audit record and telemetry captured from a sandboxed execution."""

    model_config = ConfigDict(extra="ignore")

    run_id: str = Field(..., description="Unique run identifier")
    task_id: Optional[str] = Field(default=None, description="Associated task ID")
    tool_name: str = Field(..., description="Name of the tool executed")
    status: SandboxRunStatus = Field(..., description="Execution outcome status")
    exit_code: int = Field(default=0, description="Process returncode")
    execution_time_ms: float = Field(default=0.0, description="Duration of execution in milliseconds")
    peak_memory_bytes: int = Field(default=0, description="Peak memory footprint in bytes")
    test_results: list[dict[str, Any]] = Field(default_factory=list, description="Details of executed test cases")
    output: Any = Field(default=None, description="Returned payload if mode was execution")
    stdout: str = Field(default="", description="Captured standard output (redacted)")
    stderr: str = Field(default="", description="Captured standard error (redacted)")
    source_sha256: str = Field(..., description="SHA-256 of code executed in sandbox")
    timestamp: str = Field(..., description="ISO 8601 execution timestamp")


class GeneratedToolRecord(BaseModel):
    """Persisted record in versioned catalog representing an approved capability."""

    model_config = ConfigDict(extra="ignore")

    manifest: GeneratedToolManifest
    code: str
    is_enabled: bool = True
    audit_history: list[dict[str, Any]] = Field(default_factory=list)


class ToolValidationReport(BaseModel):
    """Static security and syntax evaluation report."""

    is_valid: bool
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    source_sha256: str = ""


class TrialRunRequest(BaseModel):
    """Request to execute a proposed tool within the sandbox."""

    proposal: GeneratedToolProposal
    mode: str = Field(default="test", description="'test' to run test cases, 'run' to invoke with arguments")
    runtime_arguments: Optional[dict[str, Any]] = Field(default=None, description="Arguments when mode is 'run'")


class ToolPromotionRequest(BaseModel):
    """Request by operator to promote a successful trial into the permanent registry."""

    proposal: GeneratedToolProposal
    evidence_run_id: str = Field(..., description="Run ID proving successful sandboxed execution")
    reviewer: str = Field(default="operator", description="Operator identity approving promotion")


class ToolUpdateRequest(BaseModel):
    """Request to update enabled state or rollback version of a generated tool."""

    is_enabled: Optional[bool] = None
    target_version: Optional[str] = None
